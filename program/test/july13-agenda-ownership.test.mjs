import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { assertAgendaPublishable } from '../shared/agenda-publish-gate.mjs';

const HOUSE_ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const meetingDir = path.join(HOUSE_ROOT, 'artifacts/owen-sound/meetings/2026-07-13_council-meeting-regular_03069c57');
const index = JSON.parse(fs.readFileSync(path.join(meetingDir, 'converted/subreports.index.json'), 'utf8'));
const pageHtml = fs.readFileSync(path.join(meetingDir, 'transcript/agenda-page.html'), 'utf8');

const byItem = (item) => index.items.find((row) => row.item === item);

test('July 13 canonical HTML identity and order survive malformed PDF TOC', () => {
  assert.equal(byItem('7.a').title, 'Deputation from Kristopher Stevens, Glassworks Development Co-operative Board President Re: Glassworks Village Official Plan and Rezoning Applications');
  assert.equal(byItem('8').title, 'PUBLIC FORUM');
  assert.ok(index.items.findIndex((row) => row.item === '7.a') < index.items.findIndex((row) => row.item === '8'));
});

test('4.c owns only June 23 minutes and 7.a owns all Glassworks attachments', () => {
  const minutes = fs.readFileSync(byItem('4.c').file, 'utf8');
  assert.doesNotMatch(minutes, /Glassworks|affordable ownership|employment land needs/iu);
  assert.match(minutes, /June 23, 2026|Centennial Tower/iu);
  assert.equal(byItem('7.a').extraction_method, 'attachment_pdf');
  assert.deepEqual(byItem('7.a').attachments.map((row) => row.label), [
    'Presentation - Glassworks Village Official Plan and Rezoning Applications.pdf',
    'Glassworks Village Planning Justification Report.pdf',
    'Glassworks Village Employment Land Needs Assessment.pdf',
  ]);
});

test('Glassworks has a Stage 3 overview and titled child coverage in page and TOC', () => {
  const glassworks = pageHtml.match(/<section id="section-9"[\s\S]*?(?=<section id="section-10")/u)?.[0] || '';
  assert.match(glassworks, /affordable ownership housing/iu);
  assert.match(glassworks, /employment lands? into residential|convert(?:ing)? employment/iu);
  assert.match(glassworks, /Planning Justification Report/iu);
  assert.match(glassworks, /employment (?:land )?(?:capacity|targets|surplus)/iu);
  assert.ok((glassworks.match(/<article id="section-9-child-/gu) || []).length >= 4);
  assert.match(pageHtml, /id="section-9-child-1"/u);
  assert.match(pageHtml, /href="#section-9-child-1"/u);
  assert.match(pageHtml, /<ol class="toc-children"><li><a href="#section-9-child-1">President Kristopher Stevens Advised Owen Sound Council/u);
  assert.doesNotMatch(pageHtml, /href="#section-9-child-1">7\.a Deputation[^<]+: President Kristopher Stevens/u);
});

test('publish gate rejects missing required overview and child prose', () => {
  assert.throws(() => assertAgendaPublishable([{ item: '7.a', substantive: true, long_source: true, attachments: [{}], agenda_section_summary: '', stage3_chapters: [] }]), /no Stage 3 summary/u);
  assert.throws(() => assertAgendaPublishable([{ item: '7.a', substantive: true, long_source: true, attachments: [{}], agenda_section_summary: 'A substantive overview generated by Stage 3 for the proposed planning change.', source_text: 'independent source material '.repeat(100), stage3_chapters: [] }]), /no Stage 3 child summaries/u);
});
